def _nonfinite_state(env, asset_cfg: SceneEntityCfg = SceneEntityCfg("robot")) -> torch.Tensor:
    """Terminate envs whose physics state went NaN/Inf before the next warp step."""
    data = env.scene[asset_cfg.name].data
    bad = ~torch.isfinite(data.joint_pos).all(dim=1)
    bad |= ~torch.isfinite(data.joint_vel).all(dim=1)
    bad |= ~torch.isfinite(data.root_link_pos_w).all(dim=1)
    bad |= ~torch.isfinite(data.root_link_quat_w).all(dim=1)
    bad |= ~torch.isfinite(data.root_link_lin_vel_w).all(dim=1)
    bad |= ~torch.isfinite(data.root_link_ang_vel_w).all(dim=1)
    return bad


def _part2_wall_crossings(prev_wx, prev_wy, wx, wy, wall_x: float, span_half: float):
    """Per-wheel wall-plane crossings and side/end bypasses (P3-14).

    Returns (valid_cross, side_bypass): both are bool tensors shaped like ``wx``.
    A crossing is valid only when the interpolated y at the wall plane is inside the wall span.
    """
    import torch

    delta = wx - prev_wx
    safe = delta.abs() > 1e-6
    crossing = ((prev_wx - wall_x) * (wx - wall_x) <= 0.0) & (delta.abs() < 1.0)
    frac = torch.where(safe, (wall_x - prev_wx) / torch.where(safe, delta, torch.ones_like(delta)),
                       torch.zeros_like(delta))
    wy_at = prev_wy + (wy - prev_wy) * frac
    inside = wy_at.abs() <= span_half
    return crossing & inside, crossing & (~inside)


def _part2_state_buffers(env, n: int, device):
    """Create or reset the per-env evidence buffers used by the Part2 predicate.

    The strict judge requires *evidence* (climbed onto the top landing / crossed
    the wall plane and reached climb height / was not dropped in the pile field)
    in addition to the terminal wheel state.  Buffers reset on every episode
    start (``episode_length_buf <= 1``).
    """
    import torch

    prev = getattr(env, "_part2_prev_rx", None)
    fresh = prev is None or prev.shape[0] != n
    if fresh:
        prev = torch.zeros(n, device=device)
        env._part2_max_z_near = torch.zeros(n, device=device)
        env._part2_top_seen = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_platform_top_seen = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_slope_top_seen = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_slope_top_hold = torch.zeros(n, dtype=torch.long, device=device)
        env._part2_slope_top_ok = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_wall_wheel_crossed = torch.zeros(n, 4, dtype=torch.bool, device=device)
        env._part2_wall_side_bypass = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_gap_near_crossed = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_gap_far_crossed = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_trench_top_seen = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_plum_exit_seen = torch.zeros(n, dtype=torch.bool, device=device)
        env._part2_prev_wx = torch.zeros(n, 4, device=device)
        env._part2_prev_wy = torch.zeros(n, 4, device=device)
        env._part2_first_wall = torch.ones(n, 4, dtype=torch.bool, device=device)
    reset = env.episode_length_buf <= 1
    prev[reset] = 0.0
    env._part2_max_z_near[reset] = 0.0
    env._part2_top_seen[reset] = False
    env._part2_platform_top_seen[reset] = False
    env._part2_slope_top_seen[reset] = False
    env._part2_slope_top_hold[reset] = 0
    env._part2_slope_top_ok[reset] = False
    env._part2_wall_wheel_crossed[reset] = False
    env._part2_wall_side_bypass[reset] = False
    env._part2_gap_near_crossed[reset] = False
    env._part2_gap_far_crossed[reset] = False
    env._part2_trench_top_seen[reset] = False
    env._part2_plum_exit_seen[reset] = False
    env._part2_prev_wx[reset] = 0.0
    env._part2_prev_wy[reset] = 0.0
    env._part2_first_wall[reset] = True
    env._part2_prev_rx = prev
    return env


def _part2_wheel_lowest_points(asset, wheel_ids, wheel_radius: float):
    """World-frame lowest point of each wheel collision cylinder (N,4,3).

    Shared by the success predicate and the dense trench penalty so training and
    eval use the same geometry.  Body quats are wxyz (MuJoCo/MjLab convention).
    """
    import torch
    from mjlab.utils.lab_api.math import quat_apply

    body_pos = asset.data.body_link_pos_w[:, wheel_ids, :]
    body_quat = asset.data.body_link_quat_w[:, wheel_ids, :]
    local_center = torch.tensor(PART2_WHEEL_LOCAL_CENTER, dtype=body_pos.dtype,
                                device=body_pos.device).expand_as(body_pos)
    local_axis = torch.tensor(PART2_WHEEL_LOCAL_AXIS, dtype=body_pos.dtype,
                              device=body_pos.device).expand_as(body_pos)
    center = body_pos + quat_apply(body_quat, local_center)
    axis = quat_apply(body_quat, local_axis)
    down = torch.tensor([0.0, 0.0, -1.0], dtype=body_pos.dtype, device=body_pos.device)
    a_dot = (axis * down).sum(dim=-1)
    axial = -torch.sign(a_dot).unsqueeze(-1) * PART2_WHEEL_HALF_WIDTH_M * axis
    radial = down - axis * a_dot.unsqueeze(-1)
    norm = radial.norm(dim=-1, keepdim=True).clamp_min(1e-9)
    radial = radial / norm * wheel_radius
    return center + axial + radial


def _part2_terrain_state(
    env,
    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
    wheel_radius: float = PART2_WHEEL_RADIUS_M,
    terrain_kind: str | None = None,
):
    """Per-env official Part2 success / rule-violation state from wheel poses.

    Mirrors ``@20261024_blackw/scripts/eval_blackw_part2.py``
    (``JUDGE_VERSION = v5-wheel-terminal-bands-2026-10-25``):

    * success is a terminal-state predicate on the four wheel bottoms
      (``wheel_z`` in ``[surface - 0.06, surface + 0.20]``, i.e. support band);
    * evidence is required where the judge requires it (stairs: all wheels on the
      top landing at some point; wall: base crossed the wall plane and reached
      ``climb_z_min`` near the wall; plum: no wheel below the pile-top line in
      the field, plus all four wheels on the 0.2 m exit platform);
    * violations are rules the judge treats as an invalid attempt (a wheel
      sinking into the trench slot deeper than ``gap_max_drop_m``; a
      wheel dropped below the pile-top line while base x is inside the plum
      field; falls are handled by the generic fall terminations).

    The result is cached per env step so reward / termination terms can call it
    without double-updating the evidence buffers.

    ``terrain_kind`` selects the predicate for single-terrain specialist tasks;
    when omitted the kind is taken from the sub-terrain column name (mixed task).
    """
    import torch

    step = int(getattr(env, "common_step_counter", -1))
    cache = getattr(env, "_part2_state_cache", None)
    if cache is not None and cache[0] == step:
        return cache[1], cache[2]

    asset = env.scene[asset_cfg.name]
    terrain = env.scene.terrain
    origins = terrain.env_origins
    origins = origins.to(env.device) if isinstance(origins, torch.Tensor) else torch.as_tensor(
        origins, device=env.device)
    types = torch.as_tensor(terrain.terrain_types, device=env.device)
    levels = torch.as_tensor(terrain.terrain_levels, device=env.device)
    num_rows = int(terrain.cfg.terrain_generator.num_rows)
    # The generator maps rows to ``lower + (upper-lower) * row/(rows-1)``; the
    # default range is (0, 1) but specialist runs may pin a fixed difficulty, so
    # read the actual range instead of assuming row/(rows-1).
    diff_lo, diff_hi = terrain.cfg.terrain_generator.difficulty_range
    row_t = levels.to(torch.float32) / max(1.0, float(num_rows - 1))
    difficulty = (float(diff_lo) + (float(diff_hi) - float(diff_lo)) * row_t).clamp(0.0, 1.0)
    body_names = asset.body_names
    wheel_ids = [body_names.index(f"{leg}_foot") for leg in ("FL", "FR", "RL", "RR")]
    wpos = _part2_wheel_lowest_points(asset, wheel_ids, wheel_radius)
    wx = wpos[..., 0] - origins[:, 0:1]
    wy = wpos[..., 1] - origins[:, 1:2]
    wz = wpos[..., 2]
    rx = asset.data.root_link_pos_w[:, 0] - origins[:, 0]
    ry = asset.data.root_link_pos_w[:, 1] - origins[:, 1]
    root_z = asset.data.root_link_pos_w[:, 2]
    root_vz = asset.data.root_link_lin_vel_w[:, 2]
    n = env.num_envs
    d = difficulty
    lane = ry.abs() <= PART2_LANE_HALF_WIDTH
    # Side corridor: no support/base may leave the y-bounded course before success.
    # Wall is excluded (its terminal is crossing; post-crossing drift is allowed).
    side_out = ((wy.abs() > PART2_LANE_HALF_WIDTH).any(dim=1)
                | (ry.abs() > PART2_LANE_HALF_WIDTH))
    wz_min = wz.min(dim=1).values
    wx_min = wx.min(dim=1).values
    wx_max = wx.max(dim=1).values

    success = torch.zeros(n, dtype=torch.bool, device=env.device)
    violation = torch.zeros(n, dtype=torch.bool, device=env.device)
    columns = list(terrain.cfg.terrain_generator.sub_terrains.keys())

    def branch(name):
        if terrain_kind is not None:
            return (torch.ones(n, dtype=torch.bool, device=env.device)
                    if name == terrain_kind
                    else torch.zeros(n, dtype=torch.bool, device=env.device))
        return (types == columns.index(name)) if name in columns else torch.zeros(
            n, dtype=torch.bool, device=env.device)

    def on_surface(level, tol=PART2_WHEEL_SURFACE_TOL_M, band=0.20):
        return ((wz >= (level - tol).unsqueeze(1))
                & (wz <= (level + band).unsqueeze(1))).all(dim=1)

    if "platform" in columns or terrain_kind == "platform":
        m = branch("platform")
        top = 0.10 + 0.30 * d
        _part2_state_buffers(env, n, env.device)
        on_platform = on_surface(top) & lane & (rx >= 2.0) & (rx <= 3.25)
        env._part2_platform_top_seen |= on_platform
        on_ground = ((wz >= -PART2_WHEEL_SURFACE_TOL_M)
                     & (wz <= 0.20)).all(dim=1)
        exit_x = 3.25 + PART2_PLATFORM_EXIT_CLEARANCE_M
        success |= m & env._part2_platform_top_seen & lane & on_ground & (
            rx >= exit_x) & (wx_min >= exit_x)
        violation |= m & side_out
    if "stairs" in columns or terrain_kind == "stairs":
        m = branch("stairs")
        top = 0.60 + 1.20 * d
        goal_x = 3.70
        end_x = 6.20
        _part2_state_buffers(env, n, env.device)
        env._part2_top_seen |= ((wz >= (top - PART2_WHEEL_SURFACE_TOL_M).unsqueeze(1)).all(dim=1)
                                & (rx >= goal_x))
        on_ground = ((wz >= PART2_STAIRS_WHEEL_Z_MIN)
                     & (wz <= 0.20)).all(dim=1)
        success |= m & env._part2_top_seen & lane & on_ground & (
            wx_min >= end_x + PART2_STEP_DESCEND_CLEARANCE_M) & (
            rx >= end_x + PART2_STEP_DESCEND_CLEARANCE_M) & (
            (root_z >= 0.30) & (root_z <= 0.80))
        violation |= m & side_out
    if "slope" in columns or terrain_kind == "slope":
        m = branch("slope")
        rise = torch.tan(torch.deg2rad(20.0 + 25.0 * d)) * 2.0
        _part2_state_buffers(env, n, env.device)
        top_cond = on_surface(rise) & lane & (rx >= 3.90)
        env._part2_slope_top_seen |= top_cond
        # Judge requires the landing to be held (hold_s + TERMINAL_HOLD_EXTRA_S).
        hold = torch.where(top_cond, env._part2_slope_top_hold + 1,
                           torch.zeros_like(env._part2_slope_top_hold))
        env._part2_slope_top_hold = hold
        env._part2_slope_top_ok |= hold >= PART2_SLOPE_TOP_HOLD_STEPS
        on_ground = (wz.abs() <= PART2_SLOPE_EXIT_Z_TOL).all(dim=1)
        success |= m & env._part2_slope_top_ok & lane & on_ground & (
            rx >= PART2_SLOPE_EXIT_X) & (wx_min >= PART2_SLOPE_EXIT_X) & (
            (root_z >= 0.30) & (root_z <= 0.80))
        violation |= m & side_out
    if "high_wall" in columns or terrain_kind == "high_wall":
        m = branch("high_wall")
        goal_x = 2.27
        _part2_state_buffers(env, n, env.device)
        prev_wx = env._part2_prev_wx
        prev_wy = env._part2_prev_wy
        first = env._part2_first_wall
        # Support-point projection crossing: each wheel must cross the wall plane inside the
        # wall's y span; side/end crossings are a hard violation (termination), not a reward term.
        valid_cross, side_cross = _part2_wall_crossings(
            prev_wx, prev_wy, wx, wy, PART2_WALL_X, PART2_WALL_HALF_WIDTH)
        env._part2_wall_wheel_crossed |= valid_cross & (~first)
        env._part2_wall_side_bypass |= (side_cross & (~first)).any(dim=1)
        env._part2_prev_wx = wx.detach().clone()
        env._part2_prev_wy = wy.detach().clone()
        env._part2_first_wall = torch.zeros_like(first)
        all_crossed = env._part2_wall_wheel_crossed.all(dim=1) & (~env._part2_wall_side_bypass)
        # Do not require lane/base-y after crossing: the wall-plane y span is
        # already enforced by _part2_wall_crossings; post-crossing drift is not
        # a side bypass.
        success |= m & all_crossed & (rx >= goal_x) & (
            wx_min >= PART2_WALL_X + PART2_WALL_BACK_CLEARANCE_M) & (
            wz.max(dim=1).values <= PART2_GROUND_WHEEL_TOL_M)
        violation |= m & env._part2_wall_side_bypass
    if "trench" in columns or terrain_kind == "trench":
        m = branch("trench")
        _part2_state_buffers(env, n, env.device)
        gap_w = 0.10 + 0.20 * d
        near_x = 3.80
        far_x = near_x + gap_w
        # v7.5 judge parity (2026-10-31): crossing the slot / standing on the far
        # plateau is NOT success.  The official trench continues with a 1 m exit
        # ramp (far_x+1.0 .. far_x+2.0) down to normal ground; success requires
        # traversing that ramp and returning to normal ground (all four wheels),
        # exactly like ``Part2OfficialJudge`` v7.5 (eval/.../v5_judge.py).
        ramp_end = far_x + 2.0
        exit_ground_tol = 0.08
        allowed_drop = min(0.5 * 0.30, float(wheel_radius))
        floor_z = 0.30 - allowed_drop
        # --- evidence: base crosses near/far slot edges inside the lane ---
        prev_rx = env._part2_prev_rx
        dx = (rx - prev_rx).abs()
        near_t = torch.full_like(rx, float(near_x))
        cross_near = (((prev_rx - near_t) * (rx - near_t)) <= 0.0) & (dx < 1.0) & lane
        cross_far = (((prev_rx - far_x) * (rx - far_x)) <= 0.0) & (dx < 1.0) & lane
        env._part2_gap_near_crossed |= m & cross_near
        env._part2_gap_far_crossed |= m & cross_far
        # --- evidence: all four wheels actually stood on the far plateau top ---
        plateau_band = (wz - 0.30).abs() <= (PART2_WHEEL_SURFACE_TOL_M + 0.02)
        on_far_plateau = ((rx > far_x)
                          & (wx >= far_x.unsqueeze(1)).all(dim=1)
                          & plateau_band.all(dim=1))
        env._part2_trench_top_seen |= m & on_far_plateau
        env._part2_prev_rx = torch.where(m, rx.detach(), prev_rx)
        # --- violation: wheel sinking into the slot beyond the allowed proxy ---
        in_slot = ((wx >= (near_x - 0.06)) & (wx <= (far_x + 0.06).unsqueeze(1)))
        violation |= m & (in_slot & (wz < floor_z - 0.01)).any(dim=1)
        # --- terminal (v7.5): past the exit ramp, all wheels on normal ground,
        #     trunk back in its normal walking-height range, hold via streak ---
        past_ramp = (wx >= (ramp_end + 0.02).unsqueeze(1)).all(dim=1)
        wheels_on_ground = ((wz <= exit_ground_tol).all(dim=1)
                            & (wz_min >= -0.10))
        normal_trunk = (root_z >= 0.30) & (root_z <= 0.80)
        success |= (m & env._part2_trench_top_seen
                    & env._part2_gap_near_crossed & env._part2_gap_far_crossed
                    & lane & past_ramp & wheels_on_ground & normal_trunk
                    & (rx >= ramp_end + 0.10))
        violation |= m & side_out
    if "plum" in columns or terrain_kind == "plum":
        m = branch("plum")
        # Judge parity: the `dropped` rule is gated by BASE x in cube_x_range and
        # then checks ANY wheel bottom < z_cross_min (a wheel touching the ground
        # while the base is over the pile field invalidates the attempt).
        # Barrier height is per env: the teacher's plum field carries a height
        # curriculum (5 -> 20 cm), and both the "on the pile top" band and the
        # "dropped" line scale with it.  At the official row they reduce to the
        # judge constants (0.20 m top, 0.05 m drop line).
        top_z = _plum_top_z(env)
        z_cross = plum_z_cross(top_z)
        in_field_root = ((rx >= PART2_PLUM_CUBE_X_MIN_M)
                         & (rx <= PART2_PLUM_CUBE_X_MAX_M))
        dropped = in_field_root.unsqueeze(1) & (wz < z_cross.unsqueeze(1))
        violation |= m & dropped.any(dim=1)
        _part2_state_buffers(env, n, env.device)
        env._part2_top_seen |= in_field_root & (~dropped.any(dim=1))
        # No ramps: reaching the 0.8 m exit platform near edge is evidence only;
        # success requires stepping down from its far edge to normal ground
        # (training termination = get down to the target; mirrors v5_judge.py).
        exit_platform = (lane & (rx >= PART2_PLUM_GOAL_X_M)
                         & on_surface(top_z, band=PART2_PLUM_TOP_BAND_M))
        env._part2_plum_exit_seen |= m & exit_platform
        past_exit = (wx >= (PART2_PLUM_EXIT_END_X_M + 0.02)).all(dim=1)
        wheels_on_ground = ((wz <= PART2_PLUM_EXIT_GROUND_TOL_M).all(dim=1)
                            & (wz_min >= -0.10))
        normal_trunk = (root_z >= 0.30) & (root_z <= 0.80)
        success |= (m & env._part2_plum_exit_seen & env._part2_top_seen & lane
                    & past_exit & wheels_on_ground & normal_trunk
                    & (rx >= PART2_PLUM_EXIT_END_X_M + 0.10))
        violation |= m & side_out
    if terrain_kind is not None:
        # Single-terrain specialist task: the kind is decided by the caller, so
        # zero out the other branches' (always-false) masks for clarity.
        pass
    env._part2_state_cache = (step, success, violation)
    return success, violation


def _part2_success_streak(env, asset_cfg: SceneEntityCfg = SceneEntityCfg("robot")):
    """Consecutive success-predicate steps (cached once per env step)."""
    import torch

    step = int(getattr(env, "common_step_counter", -1))
    cache = getattr(env, "_part2_streak_cache", None)
    if cache is not None and cache[0] == step:
        return cache[1]
    success, _ = _part2_terrain_state(env, asset_cfg)
    streak = getattr(env, "_part2_success_streak", None)
    if streak is None or streak.shape[0] != env.num_envs:
        streak = torch.zeros(env.num_envs, dtype=torch.long, device=env.device)
    reset = env.episode_length_buf <= 1
    streak[reset] = 0
    streak = torch.where(success, streak + 1, torch.zeros_like(streak))
    env._part2_success_streak = streak
    env._part2_streak_cache = (step, streak)
    return streak


def _part2_failure(env, asset_cfg: SceneEntityCfg = SceneEntityCfg("robot")):
    """Termination: attempt became invalid per the strict Part2 judge."""
    _, violation = _part2_terrain_state(env, asset_cfg)
    return violation


def _masked_part2_failure(
    env,
    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
    command_name: str = "twist",
    min_cmd_vx: float = 0.2,
):
    """Training-only wrapper: judge failure predicate gated by traversal intent.

    2026-10-31 velocity-tracking Phase 2 (audit BL-3b): the mixed run rehearses
    native velocity commands (standing / reverse / large lateral) on the obstacle
    terrain.  The judge-mirrored ``_part2_failure`` predicate includes the
    ``side_out`` course violation (wheel/root lateral |y| > lane half width),
    which would kill a native-command env the moment it turns, truncating exactly
    the velocity-tracking samples the run exists to collect.  This wrapper applies
    the **unchanged** predicate only to envs whose active command is a traversal
    intent (``cmd_vx > min_cmd_vx``); the predicate semantics themselves stay
    judge-mirrored (see ``check_predicate_judge_parity.py``).  Under the default
    forward-only mix every env passes the gate, so training behaviour is unchanged.
    """
    if (command_name is None) != (min_cmd_vx is None):
        raise ValueError(
            "_masked_part2_failure: command_name and min_cmd_vx must be given together"
        )
    failure = _part2_failure(env, asset_cfg=asset_cfg)
    if command_name is None or min_cmd_vx is None:
        return failure
    command = env.command_manager.get_command(command_name)
    return failure & (command[:, 0] > float(min_cmd_vx))

# NOTE: keep exactly one definition per predicate.  Training success MUST be at
# least as strict as the judge terminal state (PART2_HOLD_STEPS default 20 = 0.40 s
# >= the judge's effective 16 samples / 0.32 s; see the hold comment above).  A
# second, hold-free definition here once shadowed these and silently made training
# success easier than the judge (P0 audit 2026-10-26).


def _part2_success(env, asset_cfg: SceneEntityCfg = SceneEntityCfg("robot")):
    """Termination: four wheels held the target support terminal state."""
    streak = _part2_success_streak(env, asset_cfg)
    return streak >= PART2_HOLD_STEPS


def _platform_top_z(env):
    """Per-env platform top height from the terrain row (official 10..40 cm range)."""
    import torch

    terrain = env.scene.terrain
    gen = terrain.cfg.terrain_generator
    sub = (gen.sub_terrains or {}).get("platform")
    lo, hi = getattr(sub, "platform_height_range", (0.10, 0.40))
    levels = torch.as_tensor(terrain.terrain_levels, device=env.device).float()
    num_rows = max(1, int(gen.num_rows))
    frac = (levels / max(1.0, float(num_rows - 1))).clamp(0.0, 1.0)
    return lo + (hi - lo) * frac


def _platform_top_success(
    env,
    min_clearance: float = 0.44,
    goal_x_min: float = 1.9,
    goal_x_max: float = 3.2,
    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
):
    """Official-platform success proxy: base over the platform AND raised onto it.

    Height is row-relative: the old absolute 0.72 threshold was unreachable on the
    10 cm pilot (root z ~0.58), so the term never fired (audit P1-2, 2026-10-26).
    """
    import torch

    asset = env.scene[asset_cfg.name]
    origins = env.scene.terrain.env_origins
    x = asset.data.root_link_pos_w[:, 0] - origins[:, 0]
    z = asset.data.root_link_pos_w[:, 2]
    top = _platform_top_z(env)
    return (x >= goal_x_min) & (x <= goal_x_max) & ((z - top) >= min_clearance)


def _lane_deviation(env, max_abs_y: float = PART2_LANE_HALF_WIDTH,
                    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
                    command_name: str | None = None,
                    min_cmd_vx: float | None = None,
                    flat_column: str | None = None):
    """Terminate lateral bypass: the Part2 judge scores only inside the lane.

    ``command_name`` / ``min_cmd_vx`` opt into the 2026-10-31 velocity-tracking
    Phase-2 gate: only envs currently commanding a traversal (body-frame
    ``cmd_vx > min_cmd_vx``) are subject to the lane termination.  Standing /
    negative-speed envs are velocity-tracking samples, not course attempts.
    Leave both at ``None`` (default) for the historical unconditional rule; giving
    only one of them is a configuration error and fails loudly.  The lane
    semantics of the success predicate (``_part2_terrain_state``) are untouched.
    """
    import torch

    if (command_name is None) != (min_cmd_vx is None):
        raise ValueError(
            "_lane_deviation: command_name and min_cmd_vx must be given together "
            f"(got command_name={command_name!r}, min_cmd_vx={min_cmd_vx!r})"
        )
    asset = env.scene[asset_cfg.name]
    origins = env.scene.terrain.env_origins
    lateral = asset.data.root_link_pos_w[:, 1] - origins[:, 1]
    deviate = torch.abs(lateral) > max_abs_y
    if command_name is not None and min_cmd_vx is not None:
        command = env.command_manager.get_command(command_name)
        deviate = deviate & (command[:, 0] > float(min_cmd_vx))
    if flat_column is not None:
        # Train-only: flat command-tracking column has no course/lane semantics.
        generator = env.scene.terrain.cfg.terrain_generator
        columns = list(generator.sub_terrains.keys())
        if flat_column in columns:
            types = torch.as_tensor(env.scene.terrain.terrain_types, device=env.device)
            deviate = deviate & (types != columns.index(flat_column))
    return deviate


def _out_of_course(
    env,
    goal_name: str = "goal",
    margin: float = 0.8,
    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
):
    """Termination: robot ran past the obstacle without satisfying success.

    Prevents post-goal reward farming (goal/progress terms saturate) and keeps
    the robot on the obstacle patch instead of wandering over the flat border.
    """
    import torch

    asset = env.scene[asset_cfg.name]
    reward = torch.zeros(env.num_envs, dtype=torch.bool, device=env.device)
    goal_data = _goal_positions(env, goal_name)
    if goal_data is None:
        return reward
    goal, valid = goal_data
    root_x = asset.data.root_link_pos_w[:, 0]
    return valid & (root_x > goal[:, 0] + margin)


def _masked_out_of_course(
    env,
    goal_name: str = "goal",
    margin: float = 0.8,
    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
    command_name: str = "twist",
    min_cmd_vx: float = 0.2,
):
    """Training-only wrapper: course-exit termination gated by traversal intent.

    Companion of ``_masked_part2_failure`` for the same audit BL-3b: a native
    (standing / reverse / large-lateral) env rehearsing flat velocity tracking on
    the obstacle patch must not be killed merely for wandering past the goal-line
    margin.  The predicate itself is unchanged; under the default forward-only mix
    every env passes the gate, so the default behaviour is unchanged.
    """
    if (command_name is None) != (min_cmd_vx is None):
        raise ValueError(
            "_masked_out_of_course: command_name and min_cmd_vx must be given together"
        )
    exit_course = _out_of_course(
        env, goal_name=goal_name, margin=margin, asset_cfg=asset_cfg
    )
    if command_name is None or min_cmd_vx is None:
        return exit_course
    command = env.command_manager.get_command(command_name)
    return exit_course & (command[:, 0] > float(min_cmd_vx))
