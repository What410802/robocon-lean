"""Single source of truth for the plum field geometry.

Every number is read from ``terrain/plum/plum_spec.json`` (generated by
``terrain/gen_plum.py`` from the competition PDF figure): two 0.8x0.8x0.2 m
platforms, six 0.2 m cubes in two staggered rows, no ramps.  The old repo used
a 24-cube field with side ramps; none of those constants appear here.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

_SPEC_PATH = (
    Path(__file__).resolve().parents[7] / "terrain" / "plum" / "plum_spec.json"
)


@dataclass(frozen=True)
class PlumSpec:
    cube_centres: tuple[tuple[float, float], ...]  # scene-frame (x, y), metres
    cube_half: float
    cube_top: float
    cube_x_range: tuple[float, float]
    entry_x_range: tuple[float, float]
    exit_x_range: tuple[float, float]
    exit_end_x: float                 # far edge = step-down to normal ground
    platform_top: float
    total_x_range: tuple[float, float]

    # Judge v9 constants (eval/robocon_eval/part2/v5_judge.py).
    z_cross_min: float = 0.05         # a wheel below this while over the field = dropped
    exit_ground_tol: float = 0.08     # wheel bottom once back on normal ground
    lane_half_width: float = 0.70

    # Training widens the field window by this margin (predicates.py convention).
    field_margin: float = 0.15

    @property
    def field_x_range(self) -> tuple[float, float]:
        """Training-side ``dropped`` window (base-x gated), judge + margin."""
        return (self.cube_x_range[0] - self.field_margin,
                self.cube_x_range[1] + self.field_margin)

    @property
    def goal_x(self) -> float:
        """Base-x line the policy must cross and hold past (exit + 0.10 m)."""
        return self.exit_end_x + 0.10


def load_spec(path: Path | None = None) -> PlumSpec:
    raw = json.loads((path or _SPEC_PATH).read_text(encoding="utf-8"))
    p = raw["plum"]
    spec = PlumSpec(
        cube_centres=tuple((float(x), float(y)) for x, y in p["cube_centres"]),
        cube_half=float(p["cube_half_m"]),
        cube_top=float(p["cube_top_m"]),
        cube_x_range=(float(p["cube_x_range_m"][0]), float(p["cube_x_range_m"][1])),
        entry_x_range=(float(p["entry_platform_x_range_m"][0]),
                       float(p["entry_platform_x_range_m"][1])),
        exit_x_range=(float(p["exit_platform_x_range_m"][0]),
                      float(p["exit_platform_x_range_m"][1])),
        exit_end_x=float(p["exit_ground_x_m"]),
        platform_top=float(p["platform_top_z_m"]),
        total_x_range=(float(p["total_x_range_m"][0]),
                       float(p["total_x_range_m"][1])),
    )
    if spec.cube_centres and len(spec.cube_centres) != 6:
        raise ValueError(f"expected 6 plum cubes, got {len(spec.cube_centres)}")
    return spec


SPEC = load_spec()
